-- Additive private runtime schema. Original public foundation is untouched.
BEGIN;
CREATE SCHEMA lc_runtime;
REVOKE ALL ON SCHEMA lc_runtime FROM PUBLIC;
DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='lazy_capitalist_runtime') THEN
  CREATE ROLE lazy_capitalist_runtime NOLOGIN;
 END IF;
END $$;
SET LOCAL search_path=lc_runtime,pg_catalog;
CREATE TABLE schema_migrations(version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE video_jobs (
              id TEXT PRIMARY KEY, topic TEXT NOT NULL, provider TEXT NOT NULL,
              status TEXT NOT NULL, result TEXT, error TEXT,
              created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE system_state (id INTEGER PRIMARY KEY CHECK(id=1), paused INTEGER NOT NULL);
CREATE TABLE job_metadata (job_id TEXT PRIMARY KEY, model TEXT NOT NULL, prompt_version TEXT NOT NULL);
CREATE TABLE cost_estimates (job_id TEXT PRIMARY KEY, estimated_usd NUMERIC NOT NULL);
CREATE TABLE submissions (key TEXT PRIMARY KEY, topic TEXT NOT NULL, job_id TEXT NOT NULL);
CREATE TABLE workflow_steps (
              job_id TEXT NOT NULL REFERENCES video_jobs(id), name TEXT NOT NULL,
              status TEXT NOT NULL DEFAULT 'pending', attempts INTEGER NOT NULL DEFAULT 0,
              result TEXT, error TEXT, next_retry DOUBLE PRECISION NOT NULL DEFAULT 0,
              claim_token TEXT, updated DOUBLE PRECISION NOT NULL DEFAULT 0, PRIMARY KEY(job_id,name));
CREATE TABLE storyboards (job_id TEXT PRIMARY KEY REFERENCES video_jobs(id), script TEXT NOT NULL);
CREATE TABLE ai_usage (
              job_id TEXT PRIMARY KEY REFERENCES video_jobs(id),
              cost_usd NUMERIC NOT NULL CHECK(cost_usd >= 0 AND cost_usd < 'Infinity'::numeric), cost_kind TEXT NOT NULL,
              input_tokens INTEGER NOT NULL DEFAULT 0, output_tokens INTEGER NOT NULL DEFAULT 0);
CREATE TABLE audit_events (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id TEXT REFERENCES video_jobs(id),
              action TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE commands(id TEXT PRIMARY KEY,request_key TEXT UNIQUE NOT NULL,input TEXT NOT NULL,
              plan TEXT NOT NULL,approved_plan TEXT,status TEXT NOT NULL DEFAULT 'draft',created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE command_videos(order_id TEXT NOT NULL REFERENCES commands(id),number INTEGER NOT NULL,
              job_id TEXT UNIQUE NOT NULL REFERENCES video_jobs(id),plan_hash TEXT NOT NULL,PRIMARY KEY(order_id,number));
CREATE TABLE order_budget(key TEXT PRIMARY KEY,order_id TEXT NOT NULL REFERENCES commands(id),
              estimate_micro BIGINT NOT NULL,reserved_micro BIGINT NOT NULL,actual_micro BIGINT NOT NULL DEFAULT 0,
              created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE youtube_vault (name TEXT PRIMARY KEY, ciphertext BYTEA NOT NULL);
CREATE TABLE owner_sessions (digest TEXT PRIMARY KEY, expires DOUBLE PRECISION NOT NULL);
CREATE TABLE platform_events(id TEXT PRIMARY KEY,platform TEXT NOT NULL,channel_id TEXT NOT NULL,
      kind TEXT NOT NULL,payload TEXT NOT NULL,audit_id INTEGER,created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE platform_blocks(platform TEXT NOT NULL,channel_id TEXT NOT NULL,blocked INTEGER NOT NULL,
      review_note TEXT,PRIMARY KEY(platform,channel_id));
CREATE TABLE report_settings(id INTEGER PRIMARY KEY CHECK(id=1), value TEXT NOT NULL);
CREATE TABLE reports(id TEXT PRIMARY KEY, kind TEXT NOT NULL, scheduled_at TIMESTAMPTZ NOT NULL, payload TEXT NOT NULL);
CREATE TABLE report_alerts(event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL);
CREATE TABLE report_cooldowns(category TEXT PRIMARY KEY, last_sent DOUBLE PRECISION NOT NULL);
CREATE TABLE report_deliveries(id TEXT PRIMARY KEY, ordinal BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE, claim_token TEXT, channel TEXT NOT NULL, status TEXT NOT NULL,
              payload TEXT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0, updated DOUBLE PRECISION NOT NULL DEFAULT 0,
              retry_at DOUBLE PRECISION NOT NULL DEFAULT 0, result TEXT, error TEXT);
INSERT INTO system_state VALUES(1,0);
INSERT INTO schema_migrations(version) VALUES('private_runtime_v1');
CREATE INDEX jobs_created_idx ON video_jobs(created_at);
CREATE INDEX usage_job_idx ON ai_usage(job_id);
CREATE INDEX audit_created_idx ON audit_events(created_at);
CREATE INDEX command_video_order_idx ON command_videos(order_id);
CREATE INDEX budget_created_idx ON order_budget(created_at);
CREATE INDEX steps_claim_idx ON workflow_steps(status,updated);
CREATE INDEX outbox_claim_idx ON report_deliveries(status,retry_at,ordinal);
CREATE INDEX platform_audit_idx ON platform_events(audit_id);
CREATE INDEX commands_created_idx ON commands(created_at);
CREATE INDEX reports_schedule_idx ON reports(scheduled_at);
GRANT USAGE ON SCHEMA lc_runtime TO lazy_capitalist_runtime;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA lc_runtime TO lazy_capitalist_runtime;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA lc_runtime TO lazy_capitalist_runtime;
